// lib/nickname.ts
//
// Зумерский "позывной" для анонимного гостя пробного урока (см.
// PUBLIC_TRIAL_T_LESSON_ID в app/t-lesson/[t_lessonId]/page.tsx) —
// персонализация без регистрации/токенов: генерируется один раз на
// сервере при заходе на гостевую страницу, показывается как userName всю
// дорогу (шапка урока, экран приза).
//
// Редкость по числу слов — идея пользователя: обычно 2 слова, изредка 3
// (добавляется "вкусовое" слово в духе фастфуд-меню — Спайси Кранчи,
// Твистер и т.п.), совсем редко 4 слова с титулом ("Сэр"/"Лорд" и т.п.) —
// звучит "породнее".

const ADJECTIVES = [
	'Гениальный', 'Легендарный', 'Отчаянный', 'Смекалистый', 'Дерзкий',
	'Ушлый', 'Бесстрашный', 'Космический', 'Токсичный', 'Мифический',
	'Внезапный', 'Загадочный', 'Непобедимый', 'Шальной', 'Огненный',
	'Сонный', 'Элитный', 'Рофловый', 'Секретный', 'Бушующий',
]

const NOUNS = [
	'Шопоголик', 'Рейдер', 'Скроллер', 'Ботан', 'Мемолог', 'Гений',
	'Задрот', 'Философ', 'Стример', 'Вайбер', 'Чемпион', 'Ниндзя',
	'Магнат', 'Странник', 'Хакер', 'Кодер', 'Мыслитель', 'Экспериментатор',
]

// "Вкусовые" слова — в духе фастфуд-меню (Спайси Кранчи, Твистер и т.п.),
// добавляются к 3- и 4-словным позывным.
const FLAVOR_WORDS = [
	'Кранчи', 'Твистер', 'Наггетс', 'Стрипс', 'Комбо', 'Спайси',
	'Хрустяш', 'Ролл', 'Биг', 'Роял',
]

const TITLES = ['Сэр', 'Лорд', 'Барон', 'Граф', 'Дон', 'Магистр']

const pick = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)]

export const pickGuestNickname = (): string => {
	const roll = Math.random()
	const adj = pick(ADJECTIVES)
	const noun = pick(NOUNS)

	// 6% — 4 слова с титулом, самый редкий и "породный" вариант.
	if (roll < 0.06) {
		return `${pick(TITLES)} ${adj} ${pick(FLAVOR_WORDS)} ${noun}`
	}
	// 24% — 3 слова, добавляется вкусовое слово.
	if (roll < 0.3) {
		return `${adj} ${noun} ${pick(FLAVOR_WORDS)}`
	}
	// 70% — обычные 2 слова.
	return `${adj} ${noun}`
}
