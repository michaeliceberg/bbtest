export const hangarJokeText = (j: HangarJoke) => [j.lead, j.quote, j.tail].filter(Boolean).join(' ')

const lastPicked = new Map<number, number>()
/** Случайная фраза предмета; подряд одна и та же не выпадает. Ракета (14–20) — один набор. */
export const pickHangarJoke = (taskNum: number): string => {
    const key = taskNum >= 14 ? 14 : taskNum
    const list = HANGAR_JOKES[key]
    let i = Math.floor(Math.random() * list.length)
    if (i === lastPicked.get(key)) i = (i + 1) % list.length
    lastPicked.set(key, i)
    return hangarJokeText(list[i])
}
