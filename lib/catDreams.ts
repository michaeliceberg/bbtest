/** Верен ли ответ: у загадки с вариантами — тот же текст, у числовой — то же число (пробелы убираем, запятая = точка). */
export function isDreamRight(dream: CatDream, input: string): boolean {
    return dream.options ? input === dream.a : sameDreamAnswer(input, dream.a)
}

/** Ответ ученика → то же число, что в `a`: убираем пробелы, запятую считаем точкой. */
export function sameDreamAnswer(input: string, a: string): boolean {
    const n = (s: string) => Number(s.replace(/\s/g, '').replace(',', '.'))
    const x = n(input)
    return input.trim() !== '' && Number.isFinite(x) && x === n(a)
}
