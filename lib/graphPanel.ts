// lib/graphPanel.ts
//
// Общая логика распознавания "композитной" картинки matching-задачи
// (CONSTRUCT, Unit 10 курса физики) — общая точка правды для
// app/lesson/quiz.tsx (решает, показывать ли композит ЕЩЁ РАЗ как общую
// иллюстрацию над условием — не нужно, если он уже показан вырезками по
// группам) и app/lesson/character-change.tsx (сами вырезки). Раньше
// каждый файл определял бы это отдельно — два независимых сетевых
// запроса на одну и ту же картинку и риск разъехаться в выводе; теперь
// quiz.tsx один раз считает panelOrientation и прокидывает готовый
// результат вниз.
//
// Базовый размер ОДНОЙ панели композита (см. scripts/svg-tools/
// render_table.py и seedEGEPhysics-unit10-lesson1.ts — диаграммы
// matching-задач рисуются на канве 280×210, композит — эти же панели
// впритык рядом/друг под другом). TOLERANCE — запас на небольшой
// технологический зазор между панелями (реально ~3% по ширине у
// горизонтальных композитов, по вертикали зазора нет вовсе).
export const PANEL_W = 280
export const PANEL_H = 210
const PANEL_TOLERANCE = 0.12

export type PanelOrientation = "h" | "v"

// Определяется НЕ по названию группы (у matching-задач бывают группы
// вида "Процесс А"/"Процесс Б", чей текст выглядит так же, как у
// настоящих составных картинок, но сама картинка при этом — ОДИН график
// на двоих, а не N панелей — такое ложное срабатывание уже ловилось при
// разборе реальных данных урока), а по РЕАЛЬНЫМ пропорциям загруженного
// файла: если natural-размер совпадает (с запасом на технологический
// зазор между панелями) с N панелями 280×210 подряд по горизонтали или
// вертикали — это композит; иначе (в т.ч. пока картинка не загрузилась)
// — обычная одиночная иллюстрация.
export function detectPanelOrientation(natW: number, natH: number, n: number): PanelOrientation | null {
    if (!natW || !natH || n < 2) return null
    const closeTo1 = (x: number) => Math.abs(x - 1) < PANEL_TOLERANCE
    if (closeTo1(natW / (n * PANEL_W)) && closeTo1(natH / PANEL_H)) return "h"
    if (closeTo1(natW / PANEL_W) && closeTo1(natH / (n * PANEL_H))) return "v"
    return null
}
