let lastShort = -1
export const pickShortJoke = (): ZnJoke => {
    let i = Math.floor(Math.random() * ZN_SHORT.length)
    if (i === lastShort) i = (i + 1) % ZN_SHORT.length
    lastShort = i
    return ZN_SHORT[i]
}
