// Пререквизит: { task: N } — задание ЕГЭ освоено на PREREQ_TASK_MASTERY;
//              { tUnit: id } — тема тренажёра пройдена на PREREQ_TOPIC_DONE (доля уроков).
// Порядок в списке = порядок изучения: первый невыполненный и предлагаем.
// Только профильная математика 2027 (ege_tasks.subject = 'math_profile').

export type Prereq = { task: number } | { tUnit: number }

// 0.5 ≈ 20 из 25 задач задачника (или меньше задач + уроки тренажёра/диагностика):
