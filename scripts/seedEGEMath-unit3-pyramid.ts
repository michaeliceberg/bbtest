// ВАЖНАЯ находка при разборе этой темы: у авто-сгенерированных вариантов
// с "некруглыми" числами страница sdamgia часто отдаёт "Это задание ещё
// не решено, приводим решение прототипа" — и открытый `<div class=
// "answer">` в этом случае относится НЕ к показанным в условии числам, а
// к какому-то не всегда согласованному значению (проверено на конкретном
// примере: id=73921, условие "сторона=12, высота=√3", в самом решении
// показан прототип id=27087 "сторона=1" с честным ответом 0,25, но
// скрытый div на странице 73921 содержал "1" — не совпадает НИ с одним
// разумным пересчётом ни для условия 73921, ни для прототипа). Поэтому
// для каждого шаблона в итоге взят id САМОГО прототипа (числа тоже его
// собственные, не смешивались с числами исходного варианта) — эти
// страницы у sdamgia полностью решены и самосогласованы.
//
// Официальных вариантов ответа (Тип 2) у sdamgia для этой темы нет.
// 6 вариантов на задачу (правило проекта для "ЕГЭ Математика"), дистракторы
// подобраны индивидуально под физику/геометрию каждой конкретной задачи
// (частые ошибки школьника: забыл коэффициент 1/3 у объёма пирамиды,
// забыл увести корень/квадрат при масштабировании, перепутал деление
// объёма получившимися частями сечения, взял не тот кусок при разбиении
// плоскостью и т.п.) — не одна формула на все подряд.
//
// Диаграммы — 21 из 24 задач с иллюстрацией. Не скопированы из оригинала
// (чужой домен/стиль) — геометрия каждого исходного SVG (сколько вершин,
// какие рёбра/грани скрыты по невидимости, что именно подсвечено) сначала
// разобрана визуально (см. общую методологию в корневом CLAUDE.md), затем
// перерисована заново в палитре проекта (тёмный фон #151F23, основные
